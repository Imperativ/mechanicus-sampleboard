'use strict';
const { chromium } = require('../tools/browser-check/node_modules/playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const checks = [];
  const state = () => page.evaluate(() => ({ state: boardDebug.state, count: boardDebug.totalCount, visible: boardDebug.visibleCount, active: boardDebug.activeCount, volume: boardDebug.volume, ids: boardDebug.activeIds }));
  try {
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
    await page.waitForFunction(() => window.boardDebug && boardDebug.totalCount > 0);
    assert.equal((await state()).count, manifest.samples.length);
    assert.equal((await state()).volume, .35);
    assert.equal((await state()).active, 0);
    checks.push('file:// boot: actual manifest, all pads, 35% volume, no autoplay');
    await page.selectOption('#character', 'Faustinius');
    assert.equal((await state()).visible, manifest.samples.filter(s => s.character === 'Faustinius').length);
    await page.selectOption('#source', 'heretek');
    assert.equal((await state()).visible, 0);
    assert.equal(await page.locator('#empty').isVisible(), true);
    await page.selectOption('#source', '');
    await page.selectOption('#character', '');
    await page.selectOption('#group', 'Tuna Samples');
    assert.equal((await state()).visible, 13);
    checks.push('Character/group/source filters and empty state');
    const first = page.locator('.pad:not([hidden])').first();
    await first.locator('.pad-main').click();
    await page.waitForFunction(() => boardDebug.activeCount === 1 && document.querySelector('#status').textContent.startsWith('Wiedergabe:'));
    await page.waitForFunction(() => parseFloat(document.querySelector('.pad.playing .progress-fill').style.width) > 0);
    assert.equal(await first.locator('.pad-main').getAttribute('aria-pressed'), 'true');
    checks.push('Actual local WAV decode/play plus progressing position');
    await page.locator('.pad:not([hidden])').nth(1).locator('.pad-main').click();
    assert.equal((await state()).active, 1);
    await page.keyboard.press('Escape');
    assert.equal((await state()).active, 0);
    checks.push('Exclusive playback and Escape stop-all');
    await page.check('#overlap');
    await first.locator('.pad-main').click();
    await page.locator('.pad:not([hidden])').nth(1).locator('.pad-main').click();
    assert.equal((await state()).active, 2);
    await page.click('#stop-all');
    await page.uncheck('#overlap');
    checks.push('Overlap switch permits two real simultaneous clips');
    await first.locator('input[type=checkbox]').check();
    await first.locator('.pad-main').click();
    const firstSample = manifest.samples.find(s => s.id === 'binharic-01');
    await page.waitForTimeout((firstSample.duration + .5) * 1000);
    assert.equal((await state()).active, 1);
    await page.keyboard.press('Escape');
    await first.locator('input[type=checkbox]').uncheck();
    checks.push('Loop remains playing past clip duration');
    await page.locator('h1').click();
    await page.keyboard.press('1');
    await page.waitForFunction(() => boardDebug.activeCount === 1);
    await page.keyboard.press('Escape');
    await page.fill('#search', '');
    await page.locator('#search').focus();
    await page.keyboard.press('1');
    assert.equal((await state()).active, 0);
    assert.equal(await page.inputValue('#search'), '1');
    await page.fill('#search', '');
    checks.push('Visible-pad keyboard shortcuts; typing in controls never triggers audio');
    await page.evaluate(() => { const input = document.querySelector('#volume'); input.value = '20'; input.dispatchEvent(new Event('input', { bubbles: true })); });
    assert.equal((await state()).volume, .2);
    assert.equal(await page.textContent('#volume-value'), '20 %');
    checks.push('Live master-volume change');
    for (const format of ['wav', 'mp3']) {
      const anchor = first.locator(`a[download][href$=".${format}"]`);
      const href = await anchor.getAttribute('href');
      assert.ok(fs.existsSync(path.resolve(root, href)), href);
    }
    assert.ok((await first.locator('a[aria-label^="Quelle"]').getAttribute('href')).includes('tuna.voicemod.net/sound/54837fc4'));
    checks.push('Actual WAV/MP3 download paths and per-sample source links');
    await page.selectOption('#group', '');
    await page.selectOption('#character', 'Faustinius');
    await page.evaluate(() => { const input = document.querySelector('#volume'); input.value = '35'; input.dispatchEvent(new Event('input', { bubbles: true })); });
    await page.screenshot({ path: path.join(root, 'logs', 'sampleboard-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: path.join(root, 'logs', 'sampleboard-mobile.png') });
    checks.push('Responsive 390px layout has no horizontal overflow');
    const fixtureDir = fs.mkdtempSync(path.join(root, 'tests', 'browser-fixture-'));
    try {
      const baseHTML = fs.readFileSync(path.join(root, 'index.html'), 'utf8')
        .replace('href="style.css"', 'href="../../style.css"')
        .replace('src="app.js"', 'src="../../app.js"');
      async function fixture(data) {
        const script = data === null ? '' : `<script>window.SAMPLEBOARD=${JSON.stringify(data).replace(/</g, '\\u003c')};</script>`;
        fs.writeFileSync(path.join(fixtureDir, 'index.html'), baseHTML.replace('<script defer src="samples.js"></script>', script));
        const view = await browser.newPage();
        view.on('pageerror', error => errors.push(error.message));
        await view.goto(pathToFileURL(path.join(fixtureDir, 'index.html')).href);
        await view.waitForFunction(() => window.boardDebug);
        return view;
      }
      let view = await fixture(null);
      assert.equal(await view.evaluate(() => boardDebug.state), 'missing-manifest');
      assert.ok((await view.textContent('#status')).includes('Manifest fehlt'));
      await view.close();
      checks.push('Missing manifest gives an explicit useful error, no synthetic replacement');
      const bad = structuredClone(manifest);
      bad.samples = [{ ...bad.samples[0], wav: 'absent.wav', mp3: 'absent.mp3' }];
      view = await fixture(bad);
      await view.locator('.pad-main').click();
      await view.waitForFunction(() => document.querySelector('.pad.failed'));
      assert.equal(await view.evaluate(() => boardDebug.activeCount), 0);
      assert.ok((await view.textContent('#status')).includes('Keine Ersatzsounds'));
      await view.close();
      checks.push('Missing actual audio is reported and playback state resets');
      const compressed = structuredClone(manifest);
      const tuna = compressed.samples.find(s => s.id === 'binharic-01');
      compressed.samples = [{ ...tuna, wav: '', mp3: '../../' + tuna.mp3 }];
      view = await fixture(compressed);
      await view.locator('.pad-main').click();
      await view.waitForFunction(() => boardDebug.activeCount === 1 && document.querySelector('#status').textContent.startsWith('Wiedergabe:'));
      await view.waitForFunction(() => parseFloat(document.querySelector('.pad.playing .progress-fill').style.width) > 0);
      await view.waitForFunction(() => boardDebug.activeCount === 0, { timeout: 10000 });
      assert.ok((await view.textContent('#status')).includes('beendet'));
      await view.close();
      checks.push('Actual MP3 browser decoding; natural completion resets the pad');
    } finally { fs.rmSync(fixtureDir, { recursive: true, force: true }); }
    assert.deepEqual(errors, []);
    const report = { passed: true, browser: await browser.version(), scheme: 'file://', sampleCount: manifest.samples.length, checks, pageErrors: errors };
    fs.writeFileSync(path.join(root, 'logs', 'browser-validation.json'), JSON.stringify(report, null, 2) + '\n');
    console.log(JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
